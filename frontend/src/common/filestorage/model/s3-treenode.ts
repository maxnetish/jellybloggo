import { S3Config } from './s3-config';

/**
 * Модель для элемента в иерархии в менеджеое файлов.
 */
export interface S3Treenode {
  /**
   * Уник. ид
   */
  id: string;
  /**
   * Инфо о бакете этого узла
   */
  s3Config: S3Config;
  /**
   * Строка для визуального предстваления в интерфейсе (может, не будет нужно)
   */
  label: string;
  /**
   * "путь" для этого узла, начиная с корневого "/"
   */
  prefix: string;
  /**
   * Тип потом уточним - это данные, которые приедут из s3 для некорневого элемента.
   * Корневой элемент в иерархии бакета всегда есть ("/")
   */
  payload: unknown;
}
