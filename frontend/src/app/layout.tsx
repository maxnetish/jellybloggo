/**
 * Layout — корневой макет приложения.
 * Этот компонент рендерится один раз и оборачивает ВСЕ страницы.
 * В нём задаётся базовая HTML структура: <html>, <head>, <body>.
 */

import type { Metadata } from 'next';

// next/font автоматически скачивает шрифты и оптимизирует их
// variable — CSS переменная, которую можно использовать в стилях
import { Geist, Geist_Mono } from 'next/font/google';
import './globals.css';

// Загружаем основной шрифт (заменит system-ui)
const geistSans = Geist({
  variable: '--font-geist-sans',
  subsets: ['latin'],
});

// Загружаем моноширинный шрифт для кода
const geistMono = Geist_Mono({
  variable: '--font-geist-mono',
  subsets: ['latin'],
});

/**
 * Metadata — экспортируемый объект с SEO-данными.
 * Next.js автоматически вставит их в <head> страницы.
 * Можно делать динамическую metadata для разных страниц.
 */
export const metadata: Metadata = {
  title: 'Create Next App',
  description: 'Generated by create next app',
};

/**
 * RootLayout — корневой компонент разметки.
 * Это Server Component (без 'use client') — работает на сервере.
 *
 * @param children — содержимое текущей страницы (page.tsx).
 *                   Next.js передаёт его автоматически.
 */
export default function RootLayout({ children }: LayoutProps<'/'>) {
  return (
    // <html> — корневой элемент. lang — для accessibility.
    <html
      lang='en'
      // className объединяет CSS переменные шрифтов.
      // Они доступны как var(--font-geist-sans) в tailwind.css
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      {/* <body> — сюда попадают все страницы приложения */}
      <body className='min-h-full flex flex-col'>
        {/* children — это <Page /> текущего route */}
        {children}
      </body>
    </html>
  );
}